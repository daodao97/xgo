type docAPITestReq struct {
	DisplayName string `json:"display_name"`
}

type docAPITestResp struct {
	DisplayName string `json:"display_name"`
	AvatarURL   string `json:"avatar_url"`
}

// docAPITestController mimics the common project style: handlers are methods
// that own binding and rendering themselves.
type docAPITestController struct{}

// @summary 方法源码注释
// @tags method-comment
func (d *docAPITestController) UpdateProfile(c *gin.Context) {
	// Deliberately NOT the xapp envelope: RegisterAPIDoc must never touch rendering.
	c.String(http.StatusTeapot, "raw-body")
}

type docAPIValueRecvController struct{}

// @summary 值接收者方法注释
func (d docAPIValueRecvController) Ping(c *gin.Context) {
	c.Status(http.StatusOK)
}

// @summary plain function summary
// @tags demo
func docAPITestPlainHandler(c *gin.Context) {
	c.Status(http.StatusNoContent)
}

// withOpenAPIEnabled flips Args.EnableOpenAPI and isolates apiRegistry for one test.
func withOpenAPIEnabled(t *testing.T) {
	t.Helper()
	prevEnabled := Args.EnableOpenAPI
	prevRegistry := apiRegistry
	Args.EnableOpenAPI = true
	apiRegistry = nil
	t.Cleanup(func() {
		Args.EnableOpenAPI = prevEnabled
		apiRegistry = prevRegistry
	})
}

// RegisterAPIDoc is a pure registration core: EnableOpenAPI / go-run gating is
// the caller's concern (RegisterAPI or a project-defined wrapper), so the core
// must register even with the flag off.
func TestRegisterAPIDoc_NoGatesInsideCore(t *testing.T) {
	prevEnabled := Args.EnableOpenAPI
	prevRegistry := apiRegistry
	Args.EnableOpenAPI = false
	apiRegistry = nil
	t.Cleanup(func() {
		Args.EnableOpenAPI = prevEnabled
		apiRegistry = prevRegistry
	})

	if !RegisterAPIDoc[docAPITestReq, docAPITestResp](docAPITestPlainHandler, docAPITestPlainHandler) {
		t.Fatal("core must register regardless of EnableOpenAPI")
	}
	if len(apiRegistry) != 1 {
		t.Fatalf("expected 1 registry entry, got %d", len(apiRegistry))
	}
}

// A project-defined wrapper: comments come from the source method, while the
// route (and registry Handler) carry the wrapped closure. Route matching must
// pair by the wrapped handler's pointer, and rendering stays fully custom.
func TestRegisterAPIDoc_CustomWrapMatchesRoute(t *testing.T) {
	withOpenAPIEnabled(t)

	gin.SetMode(gin.TestMode)
	ctrl := &docAPITestController{}
	wrapped := gin.HandlerFunc(func(c *gin.Context) { ctrl.UpdateProfile(c) })
	if !RegisterAPIDoc[docAPITestReq, docAPITestResp](ctrl.UpdateProfile, wrapped) {
		t.Fatal("RegisterAPIDoc must report true on success")
	}
	engine := gin.New()
	engine.PATCH("/im/me/profile", wrapped)

	CollectRouteInfo(engine)

	if len(apiRegistry) != 1 {
		t.Fatalf("expected 1 registry entry, got %d", len(apiRegistry))
	}
	info := apiRegistry[0]
	if info.Path != "/im/me/profile" || info.Method != "PATCH" {
		t.Fatalf("route matching failed: path=%q method=%q", info.Path, info.Method)
	}
	if info.Summary != "方法源码注释" {
		t.Fatalf("summary must come from the source method, got %q", info.Summary)
	}
	if info.RequestType != reflect.TypeOf(docAPITestReq{}) {
		t.Fatalf("unexpected request type %v", info.RequestType)
	}
	if info.ResponseType != reflect.TypeOf(docAPITestResp{}) {
		t.Fatalf("unexpected response type %v", info.ResponseType)
	}

	// Runtime behavior must be exactly the wrapped handler's own rendering.
	w := httptest.NewRecorder()
	req := httptest.NewRequest(http.MethodPatch, "/im/me/profile", nil)
	engine.ServeHTTP(w, req)
	if w.Code != http.StatusTeapot || w.Body.String() != "raw-body" {
		t.Fatalf("handler behavior changed: code=%d body=%q", w.Code, w.Body.String())
	}
}

