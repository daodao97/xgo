// End-to-end through genDoc: a RegisterAPIDoc-annotated route produces an
// operation with path params from the route pattern and the request body schema
// for PATCH.
func TestRegisterAPIDoc_GenDoc(t *testing.T) {
	withOpenAPIEnabled(t)

	gin.SetMode(gin.TestMode)
	ctrl := &docAPITestController{}
	handler := gin.HandlerFunc(ctrl.UpdateProfile)
	RegisterAPIDoc[docAPITestReq, docAPITestResp](handler, handler)
	engine := gin.New()
	engine.PATCH("/im/channels/:channel_id/profile", handler)

	doc, err := genDoc(engine, WithInfo("t", "1.0.0", "d"))
	if err != nil {
		t.Fatalf("genDoc: %v", err)
	}
	item, ok := doc.Paths["/im/channels/{channel_id}/profile"]
	if !ok {
		keys := make([]string, 0, len(doc.Paths))
		for k := range doc.Paths {
			keys = append(keys, k)
		}
		t.Fatalf("path not found in doc, have: %s", strings.Join(keys, ", "))
	}
	if item.Patch == nil {
		t.Fatal("PATCH operation missing")
	}
	var hasPathParam bool
	for _, p := range item.Patch.Parameters {
		if p.In == "path" && p.Name == "channel_id" {
			hasPathParam = true
		}
	}
	if !hasPathParam {
		t.Fatal("path parameter channel_id missing")
	}
	if item.Patch.RequestBody == nil {
		t.Fatal("request body missing for PATCH")
	}
}
