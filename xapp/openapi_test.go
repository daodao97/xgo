// Aligned with RegisterAPI: when the handler source cannot be resolved at all
// (here: method value with CWD outside the module, so the package dir lookup
// fails), the entry is skipped instead of being registered with empty metadata.
func TestRegisterAPIDoc_SkipsWhenCommentExtractionFails(t *testing.T) {
	withOpenAPIEnabled(t)

	wd, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	if err := os.Chdir(t.TempDir()); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		if err := os.Chdir(wd); err != nil {
			t.Fatal(err)
		}
	})

	ctrl := &docAPITestController{}
	handler := gin.HandlerFunc(ctrl.UpdateProfile)
	if RegisterAPIDoc[docAPITestReq, docAPITestResp](handler, handler) {
		t.Fatal("RegisterAPIDoc must report false when the source cannot be resolved")
	}
	if len(apiRegistry) != 0 {
		t.Fatalf("unresolvable handler source must skip registration, got %d entries", len(apiRegistry))
	}
}

